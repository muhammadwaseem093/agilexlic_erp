"""Push brand/brand.json and the logo into the Frappe app and the Next.js web app.

Usage:
    python brand/apply.py           # write generated brand files
    python brand/apply.py --check   # exit 1 if generated files are out of date (for CI)

The Docker builds use separate contexts (frappe_apps/agileclix_erp and apps/web),
so each app receives its own generated copy of the brand.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BRAND_DIR = ROOT / "brand"
ERP_APP = ROOT / "frappe_apps" / "agileclix_erp" / "agileclix_erp"
WEB_APP = ROOT / "apps" / "web"
GENERATED_NOTE = "Generated by brand/apply.py from brand/brand.json. Do not edit."

REQUIRED_KEYS = ("name", "shortName", "platformName", "tagline", "publisher", "logo", "font", "colors", "replace")
COLOR_KEYS = (
	"primary", "primaryDark", "primaryDeep", "accent", "sidebar", "sidebarHover",
	"background", "surface", "text", "muted", "border",
)


def load_brand() -> dict:
	brand = json.loads((BRAND_DIR / "brand.json").read_text(encoding="utf-8"))
	missing = [key for key in REQUIRED_KEYS if key not in brand]
	for mode in ("light", "dark"):
		missing += [f"colors.{mode}.{key}" for key in COLOR_KEYS if key not in brand["colors"].get(mode, {})]
	if missing:
		raise SystemExit(f"brand.json is missing: {', '.join(missing)}")
	if not (BRAND_DIR / brand["logo"]).is_file():
		raise SystemExit(f"Logo file not found: brand/{brand['logo']}")
	return brand


def kebab(name: str) -> str:
	return "".join(f"-{c.lower()}" if c.isupper() else c for c in name)


def css_vars(colors: dict) -> str:
	return "\n".join(f"\t--ac-{kebab(key)}: {value};" for key, value in colors.items())


def desk_css(brand: dict, logo_url: str) -> str:
	font = brand["font"]
	font_import = f'@import url("{font["googleFontsUrl"]}");\n\n' if font.get("googleFontsUrl") else ""
	return (
		f"/* {GENERATED_NOTE} */\n{font_import}"
		f":root {{\n{css_vars(brand['colors']['light'])}\n"
		f"\t--ac-font: \"{font['family']}\", \"Segoe UI\", system-ui, sans-serif;\n"
		f"\t--ac-radius: {brand.get('radius', '10px')};\n"
		f"\t--ac-logo: url(\"{logo_url}\");\n"
		f"\t--ac-name: {json.dumps(brand['name'])};\n"
		f"\t--ac-tagline: {json.dumps(brand['tagline'])};\n}}\n\n"
		f"[data-theme=\"dark\"] {{\n{css_vars(brand['colors']['dark'])}\n}}\n"
	)


def desk_js(brand: dict, logo_url: str) -> str:
	runtime = {
		"name": brand["name"],
		"shortName": brand["shortName"],
		"platformName": brand["platformName"],
		"tagline": brand["tagline"],
		"publisher": brand["publisher"],
		"logo": logo_url,
		"replace": brand["replace"],
	}
	return f"// {GENERATED_NOTE}\nwindow.AGILECLIX_BRAND = {json.dumps(runtime, indent=2)};\n"


def outputs(brand: dict) -> dict[Path, bytes]:
	logo_src = BRAND_DIR / brand["logo"]
	logo_name = f"brand-logo{logo_src.suffix.lower()}"
	logo_bytes = logo_src.read_bytes()
	erp_logo_url = f"/assets/agileclix_erp/images/{logo_name}"

	erp_brand = {**brand, "logoUrl": erp_logo_url}
	web_brand = {**brand, "logoUrl": f"/{logo_name}"}

	return {
		ERP_APP / "brand.json": (json.dumps(erp_brand, indent=2) + "\n").encode(),
		ERP_APP / "public" / "images" / logo_name: logo_bytes,
		ERP_APP / "public" / "css" / "agileclix_brand.css": desk_css(brand, erp_logo_url).encode(),
		ERP_APP / "public" / "js" / "agileclix_brand.js": desk_js(brand, erp_logo_url).encode(),
		WEB_APP / "src" / "brand" / "brand.json": (json.dumps(web_brand, indent=2) + "\n").encode(),
		WEB_APP / "public" / logo_name: logo_bytes,
	}


def main() -> int:
	check = "--check" in sys.argv
	stale = []
	for path, content in outputs(load_brand()).items():
		if path.is_file() and path.read_bytes() == content:
			continue
		stale.append(path.relative_to(ROOT))
		if not check:
			path.parent.mkdir(parents=True, exist_ok=True)
			path.write_bytes(content)

	if check and stale:
		print("Brand files are out of date. Run: python brand/apply.py")
		for path in stale:
			print(f"  {path}")
		return 1
	print("Brand is up to date." if not stale else f"Updated {len(stale)} brand file(s).")
	return 0


if __name__ == "__main__":
	sys.exit(main())
